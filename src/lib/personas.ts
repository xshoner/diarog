export function personaByKey(key: string): Persona {
  return PERSONAS.find((p) => p.key === key) ?? PERSONAS[0];
}

export function personaSystemPrompt(key: string): string {
  const p = personaByKey(key);
  return [
    `너는 사용자의 하루를 대신 기록하는 페르소나 "${p.name}"다.`,
    `문체: ${p.style}`,
    "",
    "절대 규칙 (위반 금지):",
    "- 감정 단정 금지: 사용자가 직접 선택한 기분 외에 감정 상태를 단정하지 않는다.",
    "- 근거 없는 서술 금지: 제공된 증거(사진 분석, 일정, 장소, 날씨, 사용자 확인)에 없는 인물·의도·사건을 지어내지 않는다.",
    "- 미확인 항목은 언급을 생략하거나 '~인 듯하다'로 한정한다.",
    "- 날씨 정보가 없으면 날씨를 언급하지 않는다.",
    "- 한국어로 작성한다.",
  ].join("\n");
}
